"""Rewrite the protocol reference in docs/fleet.md from fleet/protocol.py.

    python shared/modules/fleet/write_reference.py          # rewrite it
    python shared/modules/fleet/write_reference.py --check  # exit 1 if stale

The block between the two markers is generated; tests/test_reference.py
fails when it differs, so the documented protocol is the coded one.
Not part of the image.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from fleet.protocol import reference_markdown  # noqa: E402

DOC = HERE.parents[2] / "docs" / "fleet.md"
START = "<!-- protocol-reference:start (generated by shared/modules/fleet/write_reference.py) -->"
END = "<!-- protocol-reference:end -->"


def render(text: str) -> str:
    head, sep, rest = text.partition(START)
    _, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        raise SystemExit(f"{DOC}: the reference markers are missing")
    return f"{head}{START}\n\n{reference_markdown()}\n{END}{tail}"


def main(argv: list[str]) -> int:
    current = DOC.read_text()
    wanted = render(current)
    if "--check" in argv:
        if current != wanted:
            print(f"{DOC} is stale: run python {Path(__file__).relative_to(HERE.parents[2])}")
            return 1
        return 0
    DOC.write_text(wanted)
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
