# ───────────────────────── classification ─────────────────────────
class TestCategoryMapping:
    @pytest.mark.parametrize(
        ("subdir", "expected"),
        [
            ("websites", "topsites"),
            ("Netflix", "netflix"),
            ("DNS_Resolvers", "dns"),
            ("Custom", "custom"),
            ("HTTP", "http"),
            ("TCP", "tcp"),
            ("CPE", "cpe"),
            # legacy directory names must keep working
            ("TopSites", "topsites"),
            ("resolvers", "dns"),
            # unmapped directory
            ("Weird", "unknown"),
        ],
    )
    def test_directory_to_category(self, subdir, expected):
        rrd = f"/var/lib/smokeping/{subdir}/Target.rrd"
        assert rrd2influx.category_for(rrd, "/var/lib/smokeping") == expected

    def test_every_section_cpe_discovery_writes_has_a_category(self):
        """The CPE section is not generated by config-manager, so nothing
        else reminds anyone to map it: CPE_IPv4 exported as "unknown"."""
        import cpe_discovery

        fragment = cpe_discovery.build_cpe_targets("192.0.2.1", "2001:db8::1")
        sections = [line[2:].strip() for line in fragment.splitlines()
                    if line.startswith("+ ")]
        assert sections
        for section in sections:
            assert section in rrd2influx.CATEGORY_MAP
            rrd = f"/var/lib/smokeping/{section}/CPE_IPv4.rrd"
            assert rrd2influx.category_for(rrd, "/var/lib/smokeping") == "cpe"

    def test_rrd_at_root_is_unknown(self):
        rrd = "/var/lib/smokeping/Target.rrd"
        assert rrd2influx.category_for(rrd, "/var/lib/smokeping") == "unknown"

    def test_measurement_selection(self):
        base = "/var/lib/smokeping"
        assert rrd2influx.measurement_for(f"{base}/DNS_Resolvers/Google.rrd", base) == "dns_latency"
        assert rrd2influx.measurement_for(f"{base}/resolvers/Google.rrd", base) == "dns_latency"
        assert rrd2influx.measurement_for(f"{base}/websites/Google.rrd", base) == "latency"
        assert rrd2influx.measurement_for(f"{base}/HTTP/Google_h2.rrd", base) == "http_latency"
        assert rrd2influx.measurement_for(f"{base}/TCP/Google_tcp443.rrd", base) == "tcp_latency"

    def test_http_probe_type_comes_from_the_version_suffix(self):
        base = "/var/lib/smokeping"
        assert rrd2influx.probe_type_for(f"{base}/HTTP/Google_h1.rrd", base) == "http1"
        assert rrd2influx.probe_type_for(f"{base}/HTTP/Google_h2.rrd", base) == "http2"
        assert rrd2influx.probe_type_for(f"{base}/HTTP/Google_h3.rrd", base) == "http3"
        # an HTTP target added without a suffix is still HTTP, not fping
        assert rrd2influx.probe_type_for(f"{base}/HTTP/Site.rrd", base) == "http"
        assert rrd2influx.probe_type_for(f"{base}/TCP/Google_tcp443.rrd", base) == "tcpping"

    def test_probe_type(self):
        base = "/var/lib/smokeping"
        assert rrd2influx.probe_type_for(f"{base}/DNS_Resolvers/Google.rrd", base) == "dns"
        assert rrd2influx.probe_type_for(f"{base}/websites/Google6.rrd", base) == "fping6"
        assert rrd2influx.probe_type_for(f"{base}/websites/Google.rrd", base) == "fping"
        # '6' in the middle of a name must NOT trigger fping6 any more
        assert rrd2influx.probe_type_for(f"{base}/websites/S6Site.rrd", base) == "fping"


