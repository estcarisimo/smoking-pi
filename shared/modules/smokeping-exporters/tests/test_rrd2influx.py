# ───────────────────────── dashboards ─────────────────────────
class TestDashboardsAreValidJson:
    def test_all_dashboard_json_files_parse(self):
        files = sorted(GRAFANA_DASHBOARDS.glob("dashboards/**/*.json"))
        assert len(files) >= 9, f"expected >= 9 dashboards, found {len(files)}"
        for path in files:
            with open(path) as fh:
                dashboard = json.load(fh)
            assert dashboard.get("uid"), f"{path.name} has no uid"

    def test_panel_ids_are_unique_per_dashboard(self):
        """Collapsed rows nest their panels: a duplicate id hides there, and
        viewPanel/editPanel links then open the wrong panel."""
        def walk(panels):
            for panel in panels:
                yield panel
                yield from walk(panel.get("panels") or [])

        for path in sorted(GRAFANA_DASHBOARDS.glob("dashboards*/**/*.json")):
            with open(path) as fh:
                ids = [p["id"] for p in walk(json.load(fh).get("panels") or [])
                       if isinstance(p.get("id"), int)]
            assert len(ids) == len(set(ids)), f"{path.name}: duplicate panel ids"

    def test_all_influx_dashboards_carry_smokeping_tag_and_links(self):
        files = sorted(GRAFANA_DASHBOARDS.glob("dashboards/**/*.json"))
        for path in files:
            with open(path) as fh:
                dashboard = json.load(fh)
            assert "smokeping" in dashboard.get("tags", []), path.name
            link_tags = [t for link in dashboard.get("links", [])
                         for t in link.get("tags", [])]
            assert "smokeping" in link_tags, f"{path.name} missing dashboards link"

    def test_what_is_measured_bars_list_both_vocabularies_in_order(self):
        """The bar charts name every category and kind in a Flux array: a
        category added to taxonomy.yaml or a kind added to asn.KINDS without
        them would draw last under its raw id."""
        import re

        from common import asn

        taxonomy = (MODULE_DIR.parent / "config-manager" / "templates"
                    / "taxonomy.yaml").read_text()
        block = taxonomy.split("\ncategories:\n", 1)[1].split("\nrules:", 1)[0]
        categories = re.findall(r"^  ([a-z_]+):$", block, re.MULTILINE)
        with open(GRAFANA_DASHBOARDS / "dashboards" / "Connection"
                  / "connectivity_quality.json") as fh:
            row = next(p for p in json.load(fh)["panels"]
                       if p["title"] == "What is measured (service labels)")
        queries = {p["title"]: p["targets"][0]["query"] for p in row["panels"]}
        listed = re.findall(r'\{category: "([a-z_]+)"',
                            queries["Targets per service category"])
        assert listed == categories
        listed = re.findall(r'\{kind: "([a-z_]+)"',
                            queries["Targets per delivery kind"])
        assert listed == list(asn.KINDS)


# ───────────────────── skip unchanged RRDs ─────────────────────
class TestRRDChangedSince:
    def test_untouched_rrd_is_skipped(self, tmp_path):
        # SmokePing's step is 300s but the exporter loops every 60s, so most
        # cycles have nothing new; re-fetching all of them was ~40 wasted
        # subprocess spawns per minute.
        rrd = tmp_path / "Google.rrd"
        rrd.write_text("x")
        os.utime(rrd, (1000, 1000))
        assert rrd2influx._rrd_changed_since(str(rrd), 2000) is False

    def test_written_rrd_is_processed(self, tmp_path):
        rrd = tmp_path / "Google.rrd"
        rrd.write_text("x")
        os.utime(rrd, (3000, 3000))
        assert rrd2influx._rrd_changed_since(str(rrd), 2000) is True

    def test_equal_mtime_is_not_a_change(self, tmp_path):
        rrd = tmp_path / "Google.rrd"
        rrd.write_text("x")
        os.utime(rrd, (2000, 2000))
        assert rrd2influx._rrd_changed_since(str(rrd), 2000) is False

    def test_unstatable_rrd_assumes_changed(self, tmp_path):
        # Failing open matters: a stat error must never silently stop a target
        # from being exported.
        assert rrd2influx._rrd_changed_since(str(tmp_path / "gone.rrd"), 2000) is True


