#!/usr/bin/env python3
"""Derive shared/modules/common/data/asn_roles.csv from Linnaeus's labels.

A maintainer tool, not a `smoking-pi` command: it reads a file the
maintainer downloaded, and its output is a reviewed commit.

Linnaeus (Piotto et al., arXiv 2603.13649; github.com/NU-AquaLab/linnaeus,
MIT) releases about two thousand hand-labeled ASes, several roles each, in
data/released/<release>/labels/hierarchical.csv (asn, as_name,
top_level_category, sub_category). This keeps one kind per AS, from the
roles that say who delivers a measured target, and drops the rest
(government, finance, enterprise... are an AS's owner, not a delivery
role; those ASes stay `other`):

    python3 shared/scripts/build-asn-roles.py hierarchical.csv --release 202506
    python3 shared/scripts/build-asn-roles.py hierarchical.csv --release 202506 --check

common/asn.py's KNOWN table wins over this file; this file wins over the
AS-name heuristics.
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "shared" / "modules" / "common" / "data" / "asn_roles.csv"

# (top level, sub level or "" for any) -> our kind, in precedence order: an
# AS with several roles takes the first that matches. Access comes first: a
# carrier that also runs a CDN or hosting is, for a target answering from
# its addresses, most often the ISP's own cache or service, close to home.
PRECEDENCE: list[tuple[str, str, str]] = [
    ("Access", "", "access"),
    ("Mobile", "", "access"),
    ("Satellite", "", "access"),
    ("ContentProvider", "CDN", "cdn"),
    ("ContentProvider", "Cloud", "cloud_origin"),
    ("ContentProvider", "Hosting", "cloud_origin"),
    ("ContentProvider", "", "content_network"),
    ("Transit", "", "transit"),
    ("DNS", "", "dns_infrastructure"),
    ("EducationalResearch", "", "academic"),
]


def kind_of(roles: set[tuple[str, str]]) -> str | None:
    """Our kind for an AS's set of (top level, sub level) roles, or None."""
    for top, sub, kind in PRECEDENCE:
        if any(t == top and (not sub or s == sub) for t, s in roles):
            return kind
    return None


def derive(rows) -> list[tuple[int, str, str]]:
    """(asn, operator, kind) rows, sorted by ASN, from hierarchical.csv rows."""
    roles: dict[int, set[tuple[str, str]]] = {}
    names: dict[int, str] = {}
    for row in rows:
        try:
            asn = int(row["asn"])
        except (KeyError, TypeError, ValueError):
            continue
        roles.setdefault(asn, set()).add((row.get("top_level_category") or "",
                                          row.get("sub_category") or ""))
        names.setdefault(asn, (row.get("as_name") or "").strip())
    out = []
    for asn in sorted(roles):
        kind = kind_of(roles[asn])
        if kind:
            out.append((asn, names[asn] or f"AS{asn}", kind))
    return out


def render(derived: list[tuple[int, str, str]], release: str) -> str:
    buf = io.StringIO()
    buf.write(
        "# AS delivery roles, derived from Linnaeus's hand-labeled ASes.\n"
        f"# Source: github.com/NU-AquaLab/linnaeus, data/released/{release}/labels/"
        "hierarchical.csv\n"
        "# (Piotto et al., arXiv 2603.13649). MIT License, Copyright (c) 2024 Esteban\n"
        "# Carisimo: see LINNAEUS-LICENSE next to this file.\n"
        "# Generated by shared/scripts/build-asn-roles.py; do not edit by hand.\n"
        "# One kind per AS (the script's PRECEDENCE); common/asn.py KNOWN wins.\n")
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["asn", "operator", "kind"])
    writer.writerows(derived)
    return buf.getvalue()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__.splitlines()[0],
        epilog="Maintainer tool, not a smoking-pi command: its output is a commit.")
    parser.add_argument("labels", type=Path, help="Linnaeus labels/hierarchical.csv")
    parser.add_argument("--release", required=True, help="the Linnaeus release, e.g. 202506")
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="exit 1 if --out is stale")
    args = parser.parse_args(argv)
    with open(args.labels, newline="", encoding="utf-8") as fh:
        text = render(derive(csv.DictReader(fh)), args.release)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"stale: {args.out} -- run {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{args.out.name} is current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
